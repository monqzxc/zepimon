// Builds src/generated/egg-moves.js from PokéAPI, using the same rules as pokemon_data/generate_pokemon_egg_moves.py:
// Pokemon #1-493, moves learned by "egg" in any Gen II-IV version group. Egg moves are merged per evolution chain
// (hatdog-app/data/pokemon_species.csv), so a family shares what its baby or first stage can inherit.
// Usage: node scripts/build-egg-moves.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { species } from '../src/generated/catalog.js'

const BASE = 'https://pokeapi.co/api/v2'
const COUNT = 493
const VERSION_GROUPS = new Set(['gold-silver', 'crystal', 'ruby-sapphire', 'emerald', 'firered-leafgreen', 'diamond-pearl', 'platinum', 'heartgold-soulsilver'])
const TYPES = new Set(['normal', 'fire', 'water', 'electric', 'grass', 'ice', 'fighting', 'poison', 'ground', 'flying', 'psychic', 'bug', 'rock', 'ghost', 'dragon', 'dark', 'steel', 'fairy'])
const CLASSES = new Set(['physical', 'special', 'status'])

async function get(path, attempt = 0) {
  try {
    const response = await fetch(BASE + path, { headers: { 'User-Agent': 'zepimon-egg-moves/1.0' } })
    if (!response.ok) throw new Error(`${response.status} ${path}`)
    return await response.json()
  } catch (error) {
    if (attempt >= 3) throw error
    await new Promise(resolve => setTimeout(resolve, 1500 * (attempt + 1)))
    return get(path, attempt + 1)
  }
}

async function pool(items, worker, size = 6) {
  const results = new Array(items.length)
  let next = 0
  await Promise.all(Array.from({ length: size }, async () => {
    while (next < items.length) { const index = next++; results[index] = await worker(items[index]) }
  }))
  return results
}

const names = Object.fromEntries(Object.entries(species).map(([name, { id }]) => [id, name]))
const chainOf = {}
for (const line of readFileSync(new URL('../../hatdog-app/data/pokemon_species.csv', import.meta.url), 'utf8').trim().split(/\r?\n/).slice(1)) {
  const [id, , , , chain] = line.split(',')
  chainOf[Number(id)] = Number(chain)
}

let done = 0
const learnsets = await pool(Array.from({ length: COUNT }, (_, i) => i + 1), async id => {
  const pokemon = await get(`/pokemon/${id}/`)
  if (++done % 50 === 0) console.log(`Fetched ${done}/${COUNT} Pokemon`)
  return { id, moves: pokemon.moves.filter(entry => entry.version_group_details.some(detail =>
    detail.move_learn_method.name === 'egg' && VERSION_GROUPS.has(detail.version_group.name))).map(entry => entry.move.name) }
})

const keys = [...new Set(learnsets.flatMap(entry => entry.moves))].sort()
const details = await pool(keys, async key => {
  const move = await get(`/move/${key}/`)
  const name = move.names.find(item => item.language.name === 'en')?.name ?? key
  const type = move.type.name, kind = move.damage_class.name, power = move.power
  if (!TYPES.has(type) || !CLASSES.has(kind) || !(power === null || Number.isInteger(power))) throw new Error(`Unexpected move data for ${key}`)
  return [key, [name, type, kind === 'status' ? 0 : power ?? 0]]
})
console.log(`Fetched ${keys.length} egg moves`)

// One sorted move list per evolution chain; every catalog species points at its chain's list.
const chains = new Map()
for (const { id, moves } of learnsets) {
  const chain = chainOf[id] ?? -id
  chains.set(chain, new Set([...(chains.get(chain) || []), ...moves]))
}
const lists = []
const listIndex = new Map()
const families = {}
for (let id = 1; id <= COUNT; id++) {
  const moves = [...(chains.get(chainOf[id] ?? -id) || [])].sort()
  if (!moves.length || !names[id]) continue
  const signature = moves.join('|')
  if (!listIndex.has(signature)) { listIndex.set(signature, lists.length); lists.push(moves) }
  families[names[id]] = listIndex.get(signature)
}

const output = `// Generated by scripts/build-egg-moves.mjs from PokéAPI (Gen II-IV egg learnsets, Pokemon #1-493). Do not edit.
// moves: key -> [English name, type, power (0 for status moves)]. lists: egg moves per evolution chain. species: name -> list index.
export const eggMoveData = ${JSON.stringify({ moves: Object.fromEntries(details), lists, species: families })}
`
writeFileSync(new URL('../src/generated/egg-moves.js', import.meta.url), output)
console.log(`Wrote src/generated/egg-moves.js: ${Object.keys(families).length} species, ${lists.length} chains, ${keys.length} moves`)
