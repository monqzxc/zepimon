"""Prepare front-facing phone reaction frames, without writing to the watch project."""
import concurrent.futures
import io
import json
import urllib.request
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
REV = '0ecb1115129ccb7eb3a7e0dc3718dc263ab84011'
CACHE = ROOT / '.expo/walking-source'
OUT = ROOT / 'assets/walking'
OUT.mkdir(parents=True, exist_ok=True)
catalog = json.loads((ROOT / 'scripts/walking-catalog.json').read_text(encoding='utf-8'))

def fetch(path):
    cached = CACHE / path
    watch_cache = ROOT.parent / 'hatdog-app/data/walk-source' / path
    if cached.exists():
        return cached.read_bytes()
    if watch_cache.exists():
        return watch_cache.read_bytes()
    data = urllib.request.urlopen(f'https://raw.githubusercontent.com/rh-hideout/pokeemerald-expansion/{REV}/{path}', timeout=30).read()
    cached.parent.mkdir(parents=True, exist_ok=True)
    cached.write_bytes(data)
    return data

def build(entry):
    name, path = entry
    stem = path.removeprefix('walk/')
    directory = 'graphics/pokemon/' + stem.replace('-', '/') + '/'
    source = Image.open(io.BytesIO(fetch(directory + 'overworld.png')))
    side = source.height
    assert source.mode == 'P' and source.width in (6 * side, 8 * side), name
    variants = []
    for palette_name in ['normal', 'shiny']:
        palette = fetch(directory + 'overworld_' + palette_name + '.pal').decode().splitlines()
        assert palette[:2] == ['JASC-PAL', '0100'] and int(palette[2]) == 16
        colored = source.copy()
        colored.putpalette([int(c) for row in palette[3:19] for c in row.split()])
        colored.info['transparency'] = 0
        variants.append([colored.crop((i * side, 0, (i + 1) * side, side)).convert('RGBA') for i in (0, 1)])
    boxes = [image.getbbox() for frames in variants for image in frames]
    assert all(boxes), name
    bounds = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
    entries = []
    for shiny, frames in enumerate(variants):
        paths = []
        for index, frame in enumerate(frames):
            frame = frame.crop(bounds)
            scale = 40 / max(frame.size)
            frame = frame.resize((max(1, round(frame.width * scale)), max(1, round(frame.height * scale))), Image.Resampling.NEAREST)
            canvas = Image.new('RGBA', (44, 44))
            canvas.paste(frame, ((44 - frame.width) // 2, 42 - frame.height))
            filename = f'{stem}{"-shiny" if shiny else ""}-{index}.png'
            canvas.save(OUT / filename, optimize=True)
            paths.append(f"require('../../assets/walking/{filename}')")
        entries.append('  ' + json.dumps(('Shiny ' if shiny else '') + name) + ': [' + ', '.join(paths) + ']')
    return entries

with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
    entries = [line for group in pool.map(build, catalog.items()) for line in group]
(ROOT / 'src/generated/walking.js').write_text('// Generated by scripts/build-walking-sprites.py. See SPRITE-CREDITS.md.\nexport const walkingFrames = {\n' + ',\n'.join(entries) + '\n}\n', encoding='utf-8')
print(f'Bundled {len(catalog)} Pokemon forms with normal/shiny front-facing reaction frames.')
