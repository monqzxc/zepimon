// Builds src/generated/heights.js: each species' Pokédex height in metres (its default form), keyed by the app's English
// species names (src/generated/catalog.js), from the PokeAPI CSVs in hatdog-app/data. Used to draw Pokemon true to size
// in a Legendary's lair (src/games/lair-battle.ts). Usage: node scripts/build-heights.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { species } from '../src/generated/catalog.js'

const data = new URL('../../hatdog-app/data/', import.meta.url)
const rows = file => {
  const [head, ...lines] = readFileSync(new URL(file, data), 'utf8').trim().split(/\r?\n/)
  const keys = head.split(',')
  // These CSVs only quote names with commas, which the columns read here never have.
  return lines.map(line => Object.fromEntries(line.split(',').map((value, i) => [keys[i], value])))
}
const metres = new Map(rows('pokemon.csv').filter(row => row.is_default === '1').map(row => [Number(row.species_id), Number(row.height) / 10]))
const ids = new Map(rows('pokemon_species_names.csv').filter(row => row.local_language_id === '9')
  .map(row => [row.name.replace(/’/g, "'"), Number(row.pokemon_species_id)]))
ids.set('Nidoran F', 29).set('Nidoran M', 32)
const heights = {}
for (const name of Object.keys(species)) {
  const height = metres.get(ids.get(name))
  if (!(height > 0)) throw new Error(`No height for ${name}`)
  heights[name] = height
}
writeFileSync(new URL('../src/generated/heights.js', import.meta.url),
  `// Generated by scripts/build-heights.mjs from PokeAPI CSV data (pokemon.csv, default forms). Do not edit.\n// Pokédex height in metres, by species name.\nexport const pokemonHeights = ${JSON.stringify(heights)}\n`)
console.log(`${Object.keys(heights).length} heights`)
