import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs'
import { resolve, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const watch = resolve(root, '../hatdog-app')
const generated = resolve(root, 'src/generated')
mkdirSync(generated, { recursive: true })
for (const [from, to] of [['page/catalog.js', 'catalog.js'], ['page/types.js', 'types.js'], ['shared/companion.js', 'companion.js'], ['shared/expedition.js', 'expedition.js']]) {
  copyFileSync(resolve(watch, from), resolve(generated, to))
}
writeFileSync(resolve(generated, 'companion.js'), readFileSync(resolve(generated, 'companion.js'), 'utf8').replace("from './expedition'", "from './expedition.js'"))
const source = readFileSync(resolve(generated, 'catalog.js'), 'utf8')
const catalog = vm.runInNewContext(source.replace(/export /g, '') + '\n;({sprites, shinySprites})')
const paths = [...new Set([...Object.values(catalog.sprites), ...Object.values(catalog.shinySprites)])]
const sources = []
for (const path of paths) {
  const original = resolve(watch, 'data/original-sprites', basename(path))
  const destination = resolve(root, 'assets', path)
  mkdirSync(dirname(destination), { recursive: true })
  copyFileSync(existsSync(original) ? original : resolve(watch, 'assets/bip-5-unity', path), destination)
  sources.push(`  ${JSON.stringify(path)}: require(${JSON.stringify('../../assets/' + path)})`)
}
writeFileSync(resolve(generated, 'sprites.js'), '// Generated by npm run sync:watch. Static requires bundle sprites for offline use.\nexport const spriteSources = {\n' + sources.join(',\n') + '\n}\n')
// App icons come from pokemon_data/zepimon-icon.png via scripts/build-icons.py, so syncing sprites leaves them alone.
console.log(`Synced watch contract, catalog, and ${paths.length} offline sprites.`)
