"""Pack two walking poses into each existing portrait file; no extra image files."""
import concurrent.futures
import csv
import io
import json
import urllib.request
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'data/walk-source'
REV = '0ecb1115129ccb7eb3a7e0dc3718dc263ab84011'
BASE = f'https://raw.githubusercontent.com/rh-hideout/pokeemerald-expansion/{REV}/'
CACHE.mkdir(exist_ok=True)

def fetch(path):
    target = CACHE / path
    if not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        payload = urllib.request.urlopen(BASE + path, timeout=30).read()
        target.write_bytes(payload)
    return target.read_bytes()

catalog = {}
for line in (ROOT / 'page/catalog.js').read_text(encoding='utf-8').splitlines():
    if line.startswith('export const '):
        key, value = line.removeprefix('export const ').split(' = ', 1)
        catalog[key] = json.loads(value)
species = {int(row['id']): row['identifier'].replace('-', '_') for row in
           csv.DictReader((ROOT / 'data/pokemon_species.csv').open())}
tree = CACHE / 'tree.json'
if not tree.exists():
    tree.write_bytes(urllib.request.urlopen(
        f'https://api.github.com/repos/rh-hideout/pokeemerald-expansion/git/trees/{REV}?recursive=1').read())
tree_data = json.loads(tree.read_text())
assert not tree_data.get('truncated'), 'Incomplete source tree'
paths = {item['path'] for item in tree_data['tree']}
jobs = []
missing = []
for name, meta in catalog['species'].items():
    directory = species[meta['id']]
    for form in [name] + catalog['megaForms'].get(name, []):
        folder = directory
        if form != name:
            suffix = form.removeprefix('Mega ' + name).strip().lower().replace(' ', '_')
            folder += '/mega' + ('_' + suffix if suffix else '')
        prefix = 'graphics/pokemon/' + folder + '/'
        required = [prefix + 'overworld.png', prefix + 'overworld_normal.pal', prefix + 'overworld_shiny.pal']
        if not all(path in paths for path in required):
            missing.append(form)
            continue
        jobs.append((form, folder.replace('/', '-'), required))

def build(job):
    name, stem, required = job
    source = Image.open(io.BytesIO(fetch(required[0])))
    # Source's two-frame overworld layout: south, north, west; flip west to east.
    side = source.height
    assert source.mode == 'P' and source.width in (side * 6, side * 8), (name, source.size)
    images = []
    for palette_path in required[1:]:
        palette = fetch(palette_path).decode().splitlines()
        assert palette[:2] == ['JASC-PAL', '0100'] and int(palette[2]) == 16, name
        colored = source.copy()
        colored.putpalette([int(channel) for row in palette[3:19] for channel in row.split()])
        colored.info['transparency'] = 0
        frames = [ImageOps.mirror(colored.crop((i * side, 0, (i + 1) * side, side)).convert('RGBA')) for i in (4, 5)]
        images.append(frames)
    boxes = [frame.getbbox() for frames in images for frame in frames]
    assert all(boxes), name
    bounds = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
    for shiny, frames in enumerate(images):
        sheet = Image.new('RGBA', (48, 24))
        for index, frame in enumerate(frames):
            frame = frame.crop(bounds)
            scale = min(1, 22 / max(frame.size))
            frame = frame.resize((max(1, round(frame.width * scale)), max(1, round(frame.height * scale))), Image.Resampling.NEAREST)
            canvas = Image.new('RGBA', (24, 24))
            canvas.paste(frame, ((24 - frame.width) // 2, 23 - frame.height))
            sheet.paste(canvas, (index * 24, 0))
        portrait = catalog['shinySprites' if shiny else 'sprites'][name]
        sheet.save(ROOT / 'assets/bip-5-unity' / portrait, optimize=True)
    return name, 'walk/' + stem

with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
    manifest = dict(pool.map(build, jobs))
(ROOT / 'page/walk-sprites.js').write_text('// Generated by tools/build_walk_sprites.py. See data/walk-credits.md.\nexport const walkSprites = ' + json.dumps(manifest, separators=(',', ':')) + '\n', encoding='utf-8')
(ROOT / 'data/walk-fallbacks.json').write_text(json.dumps(missing, indent=2))
(ROOT / 'data/walk-upstream-credits.md').write_bytes(fetch('CREDITS.md'))
print(f'Walking: {len(manifest)} forms, normal + shiny, two frames each; {len(missing)} static fallbacks', flush=True)
