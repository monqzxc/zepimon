import { writeFileSync } from 'node:fs'

const url = (process.env.SUPABASE_URL || '').trim().replace(/\/$/, '')
const key = (process.env.SUPABASE_PUBLISHABLE_KEY || '').trim()
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) throw new Error('Set SUPABASE_URL to your HTTPS Supabase project URL.')
let publicKey = /^sb_publishable_[A-Za-z0-9_-]+$/.test(key)
if (key.startsWith('eyJ')) {
  try { publicKey = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()).role === 'anon' } catch {}
}
if (!publicKey) throw new Error('Use a publishable or anon key. Secret and service-role keys must never be bundled.')
const content = '// Public client settings only. Generated by zepimon-sync/configure.mjs.\nexport const cloudConfig = ' + JSON.stringify({ url, key }) + '\n'
for (const file of ['../hatdog-app/shared/cloud-config.js', '../zepimon-mobile/src/generated/cloud-config.js']) {
  writeFileSync(new URL(file, import.meta.url), content)
}
console.log('Configured both apps for ' + new URL(url).hostname + '. No private credentials were written.')
